from __future__ import annotations

import json
from abc import ABC, abstractmethod
from argparse import Namespace
from pathlib import Path
from typing import Any, Mapping

import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torchvision import models

from datasets import domainnet, officehome, pacs
from datasets.utils import read_generated_records


def _build_global_model(backbone: str, num_classes: int, pretrained: bool) -> nn.Module:
    if backbone == "resnet18":
        weights = models.ResNet18_Weights.DEFAULT if pretrained else None
        model = models.resnet18(weights=weights)
    elif backbone == "resnet50":
        weights = models.ResNet50_Weights.DEFAULT if pretrained else None
        model = models.resnet50(weights=weights)
    else:
        raise ValueError(f"unsupported backbone: {backbone}")
    model.fc = nn.Linear(model.fc.in_features, num_classes)
    return model


@torch.inference_mode()
def _evaluate_global_model(model: nn.Module, loader: DataLoader, device: torch.device) -> tuple[float, float]:
    model.eval()
    correct1 = 0
    correct5 = 0
    total = 0
    for images, labels in loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)
        logits = model(images)
        predictions = logits.topk(min(5, logits.shape[1]), dim=1).indices
        correct1 += int((predictions[:, 0] == labels).sum())
        correct5 += int((predictions == labels[:, None]).any(dim=1).sum())
        total += labels.numel()
    if total == 0:
        raise RuntimeError("cannot evaluate an empty test loader")
    return 100.0 * correct1 / total, 100.0 * correct5 / total


class OSFLAlgorithm(ABC):
    """Algorithm policy that coordinates one-shot client and server stages."""

    @abstractmethod
    def run(self, args: Namespace) -> dict[str, Any]:
        raise NotImplementedError

    def train_global_classifier(
        self,
    ) -> dict[str, str]:
        """Train the shared classifier on images generated by an OSFL algorithm."""
        args = self.args
        payload = self.load_payload()
        payload_dataset = str(payload.get("dataset", args.dataset))
        if payload_dataset.lower() != args.dataset.lower():
            raise ValueError(f"--dataset={args.dataset} does not match payload dataset={payload_dataset}")
        class_names = list(payload["class_names"])
        domains = list(payload["domains"])
        if args.synthetic_data_dir:
            synthetic_root = Path(args.synthetic_data_dir).expanduser().resolve()
        elif "synthetic_data" in self.artifacts:
            synthetic_root = Path(self.artifacts["synthetic_data"])
        else:
            synthetic_root = self.default_synthetic_root(payload)
        train_records = read_generated_records(
            synthetic_root,
            class_names,
            args.prompt_template,
            args.samples_per_class,
            args.seed,
        )
        generation_summary_path = synthetic_root / "generation_summary.json"
        generation_parameters: dict[str, Any] | None = None
        if generation_summary_path.is_file():
            with generation_summary_path.open("r", encoding="utf-8") as handle:
                generation_parameters = json.load(handle)
        device = torch.device(args.device)
        if args.dataset == "DomainNet":
            dataset_module = domainnet
        elif args.dataset == "PACS":
            dataset_module = pacs
        elif args.dataset == "OfficeHome":
            dataset_module = officehome
        else:
            raise ValueError(f"unsupported dataset: {args.dataset}")
        train_loader, test_loaders = dataset_module.build_server_loaders(
            root=Path(args.data_dir).expanduser().resolve(),
            train_records=train_records,
            class_names=class_names,
            domains=domains,
            batch_size=args.server_classifier_batch_size,
            test_batch_size=args.server_classifier_test_batch_size,
            num_workers=args.num_workers,
            device=device,
            augment=False,
        )
        return self._fit_global_classifier(
            args,
            train_loader,
            test_loaders,
            len(class_names),
            f"synthetic data: {synthetic_root}",
            run_name=synthetic_root.name,
            source_path=str(synthetic_root),
            generation_parameters=generation_parameters,
        )

    def load_payload(self) -> Mapping[str, Any]:
        """Load the algorithm-specific client upload used by server training."""
        raise NotImplementedError

    def default_synthetic_root(self, payload: Mapping[str, Any]) -> Path:
        """Return the algorithm-specific generated-image directory."""
        raise NotImplementedError

    def _fit_global_classifier(
        self,
        args: Namespace,
        train_loader: DataLoader,
        test_loaders: dict[str, DataLoader],
        num_classes: int,
        source_description: str,
        run_name: str | None = None,
        source_path: str | None = None,
        generation_parameters: Mapping[str, Any] | None = None,
    ) -> dict[str, str]:
        """Optimize, evaluate and save a classifier from prepared loaders."""
        # Some CLI algorithms expose distinct output variants while sharing one
        # implementation (for example FedDoG and its class-level FedDoG-C mode).
        algorithm_name = getattr(args, "output_algorithm_name", args.algorithm)
        device = torch.device(args.device)
        train_images = len(train_loader.dataset)
        print(f"Global classifier training {source_description} ({train_images} images)")
        model = _build_global_model(args.backbone, num_classes, args.pretrained_backbone).to(device)
        optimizer = torch.optim.SGD(
            model.parameters(),
            lr=args.learning_rate,
            momentum=args.momentum,
            weight_decay=args.weight_decay,
        )
        scheduler = torch.optim.lr_scheduler.StepLR(optimizer, step_size=50, gamma=0.1)
        criterion = nn.CrossEntropyLoss()
        metrics: dict[str, dict[str, float]] = {}

        for epoch in range(1, args.server_classifier_epochs + 1):
            model.train()
            loss_sum = 0.0
            count = 0
            for images, labels in train_loader:
                images = images.to(device, non_blocking=True)
                labels = labels.to(device, non_blocking=True)
                optimizer.zero_grad(set_to_none=True)
                loss = criterion(model(images), labels)
                loss.backward()
                optimizer.step()
                loss_sum += float(loss.detach()) * labels.numel()
                count += labels.numel()
            scheduler.step()
            if count == 0:
                raise RuntimeError("no full global training batch was produced; reduce --server-classifier-batch-size")
            print(f"epoch={epoch:03d}/{args.server_classifier_epochs} loss={loss_sum / count:.5f}")
            if epoch % args.eval_every == 0 or epoch == args.server_classifier_epochs:
                metrics = {}
                for domain, loader in test_loaders.items():
                    top1, top5 = _evaluate_global_model(model, loader, device)
                    metrics[domain] = {"top1": top1, "top5": top5}
                    print(f"  {domain:10s}: top1={top1:6.2f} top5={top5:6.2f}")
                average_top1 = sum(item["top1"] for item in metrics.values()) / len(metrics)
                average_top5 = sum(item["top5"] for item in metrics.values()) / len(metrics)
                print(f"  {'average':10s}: top1={average_top1:6.2f} top5={average_top5:6.2f}")

        outputs_root = Path(__file__).resolve().parents[1] / "outputs"
        checkpoint_value = args.checkpoint_path or str(
            outputs_root / "models" / f"{algorithm_name}_{args.dataset}_{args.backbone}.pt"
        )
        checkpoint = Path(checkpoint_value).expanduser().resolve()
        saved_checkpoint: str | None = None
        if args.save_global_classifier:
            checkpoint.parent.mkdir(parents=True, exist_ok=True)
            torch.save(model.state_dict(), checkpoint)
            saved_checkpoint = str(checkpoint)
            print(f"Saved global classifier to {checkpoint}")
        else:
            print("Global classifier checkpoint not saved (use --save-global-classifier to save it)")
        samples = "all" if args.samples_per_class is None else str(args.samples_per_class)
        result_run_name = run_name or f"{algorithm_name}_shots_{args.shots_per_class}_seed_{args.seed}"
        result_name = (
            f"{result_run_name}_{args.backbone}_samples_{samples}_"
            f"epochs_{args.server_classifier_epochs}_lr_{args.learning_rate:g}_seed_{args.seed}.json"
        )
        metrics_path = (
            Path(args.results_path or outputs_root / "results" / args.dataset / result_name).expanduser().resolve()
        )
        metrics_path.parent.mkdir(parents=True, exist_ok=True)
        with metrics_path.open("w", encoding="utf-8") as handle:
            json.dump(
                {
                    "algorithm": algorithm_name,
                    "dataset": args.dataset,
                    "run_name": result_run_name,
                    "source_path": source_path,
                    "generation_parameters": generation_parameters,
                    "checkpoint": saved_checkpoint,
                    "backbone": args.backbone,
                    "num_classes": num_classes,
                    "epochs": args.server_classifier_epochs,
                    "learning_rate": args.learning_rate,
                    "momentum": args.momentum,
                    "weight_decay": args.weight_decay,
                    "pretrained_backbone": args.pretrained_backbone,
                    "samples_per_class": args.samples_per_class,
                    "seed": args.seed,
                    "train_images": train_images,
                    "domain_metrics": metrics,
                    "domain_average_top1": average_top1,
                    "domain_average_top5": average_top5,
                },
                handle,
                ensure_ascii=False,
                indent=2,
            )
        artifacts = {"metrics": str(metrics_path)}
        if saved_checkpoint is not None:
            artifacts["checkpoint"] = saved_checkpoint
        return artifacts
