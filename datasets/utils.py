from __future__ import annotations

import random
from pathlib import Path
from typing import Any, Sequence, TypeVar

import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset
from torchvision import transforms

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}
CLIP_MEAN = (0.48145466, 0.4578275, 0.40821073)
CLIP_STD = (0.26862954, 0.26130258, 0.27577711)


class PILImageRecords(Dataset):
    """Load validated image records as RGB PIL images for feature encoders."""

    def __init__(self, records: Sequence[tuple[Path, int]]) -> None:
        self.records = list(records)

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, index: int) -> tuple[Image.Image, int]:
        image_path, label = self.records[index]
        with Image.open(image_path) as image:
            return image.convert("RGB"), label


class TransformedImageRecords(Dataset):
    """Load labeled image paths and apply the server classifier transform."""

    def __init__(self, records: Sequence[tuple[Path, int]], transform: transforms.Compose) -> None:
        self.records = list(records)
        self.transform = transform

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, index: int) -> tuple[torch.Tensor, int]:
        image_path, label = self.records[index]
        with Image.open(image_path) as image:
            return self.transform(image.convert("RGB")), label


class ClipBatchCollator:
    """Apply a Hugging Face CLIP processor to a PIL image batch."""

    def __init__(self, processor: Any, image_size: int) -> None:
        self.processor = processor
        self.image_size = image_size

    def __call__(self, batch: Sequence[tuple[Image.Image, int]]) -> tuple[torch.Tensor, torch.Tensor]:
        images, labels = zip(*batch)
        resized = [image.resize((self.image_size, self.image_size), Image.Resampling.BICUBIC) for image in images]
        pixel_values = self.processor(
            images=resized,
            return_tensors="pt",
            do_resize=False,
            do_center_crop=False,
        )["pixel_values"]
        return pixel_values, torch.tensor(labels, dtype=torch.long)


def build_record_loader(
    records: Sequence[tuple[Path, int]],
    image_size: int,
    batch_size: int,
    num_workers: int,
    device: torch.device,
    shuffle: bool,
    augment: bool,
    drop_last: bool = False,
) -> DataLoader:
    """Build a classifier loader using the preprocessing chosen by a dataset module."""
    transform_steps: list[Any] = [
        transforms.Resize((image_size, image_size), interpolation=transforms.InterpolationMode.BICUBIC)
    ]
    if augment:
        # transform_steps.append(transforms.RandAugment())
        transform_steps.extend(
            [
                transforms.RandomResizedCrop(image_size, scale=(0.8, 1.0)),
                transforms.RandomHorizontalFlip(),
            ]
        )
    transform_steps.extend(
        [
            transforms.ToTensor(),
            transforms.Normalize(CLIP_MEAN, CLIP_STD),
        ]
    )
    transform = transforms.Compose(transform_steps)
    return DataLoader(
        TransformedImageRecords(records, transform),
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=device.type == "cuda",
        drop_last=drop_last,
        persistent_workers=num_workers > 0,
    )


def read_generated_records(
    root: Path,
    class_names: Sequence[str],
    prompt_template: str,
    samples_per_class: int | None,
    seed: int,
) -> list[tuple[Path, int]]:
    """Read the labeled images generated by a server-side OSFL algorithm."""
    rng = random.Random(seed)
    records: list[tuple[Path, int]] = []
    for label, class_name in enumerate(class_names):
        class_dir = root / prompt_template.format(class_name.replace("_", " "))
        if not class_dir.is_dir():
            raise FileNotFoundError(f"generated category directory not found: {class_dir}")
        images = sorted(path for path in class_dir.iterdir() if path.suffix.lower() in IMAGE_SUFFIXES)
        if samples_per_class is not None:
            if len(images) < samples_per_class:
                raise ValueError(
                    f"category {class_name!r} has {len(images)} images, "
                    f"fewer than --samples-per-class={samples_per_class}"
                )
            images = sorted(rng.sample(images, samples_per_class))
        records.extend((path, label) for path in images)
    if not records:
        raise RuntimeError(f"no synthetic training images found under {root}")
    return records


def validate_domains(value: str, available_domains: Sequence[str], dataset_name: str) -> list[str]:
    domains = [item.strip() for item in value.split(",") if item.strip()]
    unknown = sorted(set(domains) - set(available_domains))
    if unknown:
        raise ValueError(f"unknown {dataset_name} domains: {unknown}")
    if not domains:
        raise ValueError(f"at least one {dataset_name} domain is required")
    return domains


def class_images(root: Path, domain: str, class_name: str) -> list[Path]:
    class_dir = root / domain / class_name
    if not class_dir.is_dir():
        raise FileNotFoundError(f"dataset category directory not found: {class_dir}")
    images = sorted(path for path in class_dir.iterdir() if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES)
    if not images:
        raise RuntimeError(f"no supported images found in {class_dir}")
    return images


def read_folder_client(
    root: Path,
    domain: str,
    class_names: Sequence[str],
    shots_per_class: int,
    *,
    client_index: int = 0,
    clients_per_domain: int = 1,
    test_samples_per_class: int = 0,
) -> tuple[list[tuple[Path, int]], dict[int, str]]:
    """Hold out each class tail, then assign a balanced, disjoint shard to one client."""
    if clients_per_domain <= 0:
        raise ValueError("clients_per_domain must be positive")
    if not 0 <= client_index < clients_per_domain:
        raise ValueError("client_index is outside the configured client range")
    records: list[tuple[Path, int]] = []
    label_names: dict[int, str] = {}
    for label, class_name in enumerate(class_names):
        images = class_images(root, domain, class_name)
        if test_samples_per_class > 0:
            images = images[:-test_samples_per_class] if len(images) > test_samples_per_class else []
        if shots_per_class > 0:
            images = images[: shots_per_class * clients_per_domain]
        shard_index = (client_index - label) % clients_per_domain
        shard = balanced_partition(images, clients_per_domain, shard_index)
        records.extend((path, label) for path in shard)
        label_names[label] = class_name
    return records, label_names


T = TypeVar("T")


def balanced_partition(items: Sequence[T], part_count: int, part_index: int) -> list[T]:
    """Split ordered items into disjoint parts whose sizes differ by at most one."""
    if part_count <= 0:
        raise ValueError("part_count must be positive")
    if not 0 <= part_index < part_count:
        raise ValueError("part_index is outside the configured part range")
    quotient, remainder = divmod(len(items), part_count)
    start = part_index * quotient + min(part_index, remainder)
    size = quotient + (part_index < remainder)
    return list(items[start : start + size])


def read_folder_test(
    root: Path,
    domain: str,
    class_names: Sequence[str],
    samples_per_class: int | None,
) -> list[tuple[Path, int]]:
    """Read test images, optionally taking the last N per class as done by FedBiP PACS."""
    records: list[tuple[Path, int]] = []
    for label, class_name in enumerate(class_names):
        images = class_images(root, domain, class_name)
        if samples_per_class is not None:
            images = images[-samples_per_class:]
        records.extend((path, label) for path in images)
    return records
